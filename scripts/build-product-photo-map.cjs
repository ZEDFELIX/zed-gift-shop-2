const counts = {};
const out = {};
products.forEach((p, i) => {
  const hay = p.slug + " " + p.name;
  let topic = "default";
  for (const [key, re] of RULES) {
    if (re.test(hay)) {
      topic = key;
      break;
    }
  }
  const arr = TOPICS[topic] || TOPICS.default;
  const used = counts[topic] || 0;
  out[p.slug] = arr[used % arr.length];
  counts[topic] = used + 1;
});

const lines = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const body = `// AUTO-GENERATED by scripts/build-product-photo-map.cjs - do not edit by hand.
//
// Maps each product slug to a Unsplash photo id so every product shows a
// picture that matches what it actually is. All ids are verified reachable by
// scripts/validate-all-photos.cjs.
export const PRODUCT_PHOTO_BY_SLUG: Record<string, string> = {
${lines.join("\n")}
};
`;

fs.writeFileSync("scripts/product-photo.ts", body);
fs.writeFileSync("scripts/product-photo-map.json", JSON.stringify(out, null, 2));
console.log(`wrote ${Object.keys(out).length} mappings`);
