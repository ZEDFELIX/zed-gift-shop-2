// Regenerates scripts/product-photo.ts from rio-catalogue.ts.
// Every product slug is matched to a topic by name, then assigned a photo from
// that topic's list so the picture actually matches the product.
const fs = require("fs");

const catalogue = fs.readFileSync("prisma/rio-catalogue.ts", "utf8");
const slugRe = /p\(\s*"([^"]+)"\s*,\s*"([^"]+)"/g;
const products = [];
let m;
while ((m = slugRe.exec(catalogue))) products.push({ slug: m[1], name: m[2] });

// Ordered: first match wins, so put specific patterns before generic ones.
const RULES = [
  ["blanket", /\b(blanket|maasai|shuka)\b/i],
  ["mug", /\b(mug|beer|tumbler|flask|bottle|water bottle|drink)\b/i],
  ["perfume", /\b(perfume|fragrance)\b/i],
  ["watch", /\bwatch\b/i],
  ["jewelry", /\b(necklace|pendant|earring|ring|bracelet|jewellery|jewelry)\b/i],
  ["wallet", /\b(wallet|card holder|card-holder)\b/i],
  ["belt", /\bbelt\b/i],
  ["nametag", /\bname.?tag\b/i],
  ["keychain", /\bkeychain\b/i],
  ["notebook", /\b(notebook|diary|planner|journal)\b/i],
  ["desk", /\b(desk organizer|organizer|desk calendar)\b/i],
  ["award", /\b(award|trophy|crystal)\b/i],
  ["tote", /\b(tote|jute|bag)\b/i],
  ["shoes", /\b(shoes|loafers|sneakers)\b/i],
  ["tech", /\b(power bank|tech|charger)\b/i],
  ["gift", /\b(hamper|gift set|corporate|merchandise|eco-friendly)\b/i],
];

